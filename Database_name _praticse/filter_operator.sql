-- Filter Operations

-- Equal Operator

-- 27 records
select * from students where
city = 'Pondicherry'

-- not equal Operator

-- 73 records
select * from students where
city  != 'Pondicherry'

select * from students where
city  <> 'Pondicherry'

select * from students where
not city  ='Pondicherry'

-- greater than or lesser than 

--14 record
select * from students where
age <18;

